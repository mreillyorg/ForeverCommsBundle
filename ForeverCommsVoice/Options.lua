local _, V = ...
local function label(parent, text, y, template)
    local f = parent:CreateFontString(nil,"ARTWORK",template or "GameFontHighlight")
    f:SetPoint("TOPLEFT",18,y)
    f:SetText(text)
    return f
end
local controls = {}
function V:RefreshOptions()
    for _,fn in ipairs(controls) do fn() end
end
function V:BuildOptions()
    if self.settingsCategory or not CreateFrame then return end
    local f = CreateFrame("Frame")
    f.name = "Forever Comms Voice"
    f:SetSize(560,650)
    label(f,"Forever Comms Voice",-18,"GameFontNormalLarge")
    label(f,"Shared per-character language and speaking style for GuildComms and GroupComms.",-52,"GameFontHighlightSmall")
    local y = -96
    local function cycle(key, title, choices)
        label(f,title,y)
        local button = CreateFrame("Button",nil,f,"UIPanelButtonTemplate")
        button:SetSize(240,24); button:SetPoint("TOPLEFT",260,y+6)
        button:SetScript("OnClick",function()
            local voice = V:GetSettings()
            local items = type(choices)=="function" and choices() or choices
            local index=0
            for i,item in ipairs(items) do if item.id==voice[key] then index=i end end
            for n=1,#items do
                local candidate=items[((index+n-1)%#items)+1]
                if V:SetOption(key,candidate.id) then break end
            end
        end)
        local function refresh()
            local value=V:GetSettings()[key]
            local items=type(choices)=="function" and choices() or choices
            for _,item in ipairs(items) do if item.id==value then button:SetText(item.label); return end end
            button:SetText(tostring(value))
        end
        controls[#controls+1]=refresh;refresh();y=y-48
    end
    cycle("language","Message language",function() return V.languages end)
    local cb = CreateFrame("CheckButton",nil,f,"UICheckButtonTemplate")
    cb:SetSize(24,24);cb:SetPoint("TOPLEFT",15,y+5)
    cb:SetScript("OnClick",function(widget) V:SetOption("raceFilter",widget:GetChecked()==true) end)
    local raceLabel = label(f,"Suggest accents for my character's race",y)
    raceLabel:ClearAllPoints()
    raceLabel:SetPoint("TOPLEFT",50,y)
    controls[#controls+1]=function() cb:SetChecked(V:GetSettings().raceFilter) end
    controls[#controls]();y=y-48
    cycle("accent","Accent / RP voice",function() return V:GetAvailableAccents() end)
    cycle("accentStrength","Accent strength",{{id="subtle",label="Subtle (wording only)"},{id="moderate",label="Moderate (adds a catchphrase)"},{id="expressive",label="Expressive (catchphrase + emphasis)"}})
    label(f,"Applies only to messages generated by Forever Comms addons.",-345,"GameFontHighlightSmall")
    label(f,"Shared message review queue",-376,"GameFontNormalLarge")
    local function queueCycle(key, title, values, yPos)
        label(f,title,yPos)
        local b=CreateFrame("Button",nil,f,"UIPanelButtonTemplate")
        b:SetSize(230,24);b:SetPoint("TOPLEFT",260,yPos+6)
        b:SetScript("OnClick",function()
            local q=V:GetQueueSettings();local idx=0
            for i,v in ipairs(values) do if v.id==q[key] then idx=i end end
            local nextVal=values[idx % #values + 1]
            V:SetQueueOption(key,nextVal.id)
        end)
        local function refresh()
            local val=V:GetQueueSettings()[key]
            for _,v in ipairs(values) do if v.id==val then b:SetText(v.label);return end end
            b:SetText(tostring(val))
        end
        controls[#controls+1]=refresh;refresh()
    end
    local rowValues={}
    for n=1,10 do rowValues[#rowValues+1]={id=n,label=tostring(n).." rows"} end
    queueCycle("visibleRows","Rows visible (scroll for more)",rowValues,-413)
    queueCycle("sourceDisplay","Message source column",{{id="text",label="Guild / Group text"},{id="icon",label="Source icon"}},-454)
    label(f,"Auto-skip after (seconds)",-495)
    local timeoutEdit=CreateFrame("EditBox",nil,f,"InputBoxTemplate")
    timeoutEdit:SetSize(88,25);timeoutEdit:SetPoint("TOPLEFT",266,-489)
    timeoutEdit:SetAutoFocus(false);timeoutEdit:SetMaxLetters(4)
    timeoutEdit:SetScript("OnEnterPressed",function(widget)
        V:SetQueueOption("autoSkipSeconds",widget:GetText())
        widget:SetText(tostring(V:GetQueueSettings().autoSkipSeconds))
        widget:ClearFocus()
    end)
    timeoutEdit:SetScript("OnEscapePressed",function(widget)
        widget:SetText(tostring(V:GetQueueSettings().autoSkipSeconds))
        widget:ClearFocus()
    end)
    local noLimit=label(f,"0 = never",-495,"GameFontHighlightSmall")
    noLimit:ClearAllPoints();noLimit:SetPoint("TOPLEFT",374,-495)
    controls[#controls+1]=function() timeoutEdit:SetText(tostring(V:GetQueueSettings().autoSkipSeconds)) end
    controls[#controls]()
    local showCheck=CreateFrame("CheckButton",nil,f,"UICheckButtonTemplate")
    showCheck:SetSize(24,24);showCheck:SetPoint("TOPLEFT",15,-532)
    showCheck:SetScript("OnClick",function(widget) V:SetQueueOption("showOnNew",widget:GetChecked()==true) end)
    local showLabel=label(f,"Open queue when a message is added",-537)
    showLabel:ClearAllPoints();showLabel:SetPoint("TOPLEFT",50,-537)
    controls[#controls+1]=function()showCheck:SetChecked(V:GetQueueSettings().showOnNew)end
    controls[#controls]()
    local openQueue=CreateFrame("Button",nil,f,"UIPanelButtonTemplate")
    openQueue:SetSize(205,25);openQueue:SetPoint("TOPLEFT",18,-582)
    openQueue:SetText("Open message review queue")
    openQueue:SetScript("OnClick",function() V:ShowQueue(true) end)
    if Settings and Settings.RegisterCanvasLayoutCategory then
        local cat = Settings.RegisterCanvasLayoutCategory(f,f.name)
        Settings.RegisterAddOnCategory(cat)
        self.settingsCategory=cat
    elseif InterfaceOptions_AddCategory then InterfaceOptions_AddCategory(f) end
end
function V:OpenOptions()
    if not self.settingsCategory then self:BuildOptions() end
    if Settings and Settings.OpenToCategory and self.settingsCategory then
        Settings.OpenToCategory(self.settingsCategory.GetID and self.settingsCategory:GetID() or self.settingsCategory)
    elseif InterfaceOptionsFrame_OpenToCategory then
        InterfaceOptionsFrame_OpenToCategory("Forever Comms Voice")
        InterfaceOptionsFrame_OpenToCategory("Forever Comms Voice")
    end
end
SLASH_FOREVERCOMMSVOICE1 = "/fcv"
SLASH_FOREVERCOMMSVOICE2 = "/commsvoice"
SlashCmdList.FOREVERCOMMSVOICE = function(input)
    input=(input or ""):lower():match("^%s*(.-)%s*$")
    if input=="queue" or input=="review" then V:ShowQueue(true)
    elseif input=="clear" then V:SkipAll()
    else V:OpenOptions() end
end
local f=CreateFrame("Frame")
f:RegisterEvent("ADDON_LOADED")
f:SetScript("OnEvent",function(_,_,name)
    -- Compare against V.name, not the vararg: this file follows the `local _, V = ...`
    -- module pattern, so the addon name is only available via the namespace Core set.
    -- A bare ADDON here was nil, so the panel was never registered until /fcv ran.
    if name == V.name then V:GetSettings();V:BuildOptions();V.initialized=true end
end)
